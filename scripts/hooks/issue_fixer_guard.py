def _unquoted_newlines_to_separators(command: str) -> str:
    """Line continuations become spaces; unquoted newlines become ';' so every line is its own segment."""
    command = command.replace("\\\r\n", " ").replace("\\\n", " ")
    out, quote = [], None
    for ch in command:
        if quote:
            if ch == quote:
                quote = None
        elif ch in ("'", '"'):
            quote = ch
        elif ch in ("\n", "\r"):
            ch = ";"
        out.append(ch)
    return "".join(out)


def split_segments(command: str) -> list:
    lexer = shlex.shlex(_unquoted_newlines_to_separators(command), posix=True, punctuation_chars=";&|()<>")
    lexer.whitespace_split = True
    lexer.commenters = ""
    try:
        tokens = list(lexer)
    except ValueError as e:
        raise Denied(f"unparseable command ({e})")
    segments, current = [], []
    for tok in tokens:
        if tok in OPERATORS:
            if current:
                segments.append(current)
            current = []
        else:
            current.append(tok)
    if current:
        segments.append(current)
    return segments


def _strip_redirections(words: list) -> list:
    """Drops redirection operators and their targets (`> file`, `2>&1`, `< in`)."""
    out, skip = [], False
    for w in words:
        if skip:
            skip = False
            continue
        if re.fullmatch(r"[<>&]*[<>][<>&]*", w):
            skip = True
            continue
        out.append(w)
    return out


def _unwrap(words: list) -> list:
    """Skips VAR=value prefixes and wrapper programs with their options; returns [program, args...]."""
    words = list(words)
    while words:
        if ASSIGNMENT_RE.match(words[0]):
            words.pop(0)
            continue
        prog = os.path.basename(words[0])
        if prog not in WRAPPERS:
            return words
        words.pop(0)
        with_arg = WRAPPER_FLAGS_WITH_ARG.get(prog, set())
        while words and words[0].startswith("-"):
            flag = words.pop(0)
            if prog == "env" and (flag in ("-S", "--split-string") or flag.startswith("--split-string=")):
                raise Denied("env -S (string splitting) is not allowed")
            if flag in with_arg and words:
                words.pop(0)
        if prog == "env":
            while words and ASSIGNMENT_RE.match(words[0]):
                words.pop(0)
        if prog == "timeout" and words:
            words.pop(0)  # the duration
    return words


def check_git(args: list) -> None:
    i = 0
    while i < len(args) and args[i].startswith("-"):
        opt = args[i]
        if opt == "-c" or opt.startswith("-c") or opt.startswith("--config-env") or opt.startswith("--exec-path"):
            raise Denied("git -c / --config-env / --exec-path can run arbitrary commands")
        if opt in ("-C", "--git-dir", "--work-tree", "--namespace"):
            i += 2
            continue
        i += 1
    if i >= len(args):
        raise Denied("bare `git` (no subcommand)")
    sub = args[i]
    if sub not in GIT_READ_SUBCOMMANDS:
        raise Denied(f"`git {sub}` is not a read-only git subcommand (the orchestrator commits, pushes and "
                     "manages branches; never stage, commit, stash, checkout, reset, merge or push)")
    for a in args[i + 1:]:
        if any(a == d or a.startswith(d + "=") or (d == "-O" and a.startswith("-O")) for d in GIT_DENIED_ARGS):
            raise Denied(f"`git {sub} {a}` can run an external program or write a file")


def check_python(args: list) -> None:
    i = 0
    while i < len(args):
        a = args[i]
        if a in PYTHON_FLAGS_WITH_ARG:
            i += 2
            continue
        if a.startswith("-W") or a.startswith("-X"):
            i += 1
            continue
        if a == "-m":
            if i + 1 >= len(args):
                raise Denied("python -m without a module")
            if args[i + 1].split(".")[0] not in PYTHON_MODULES:
                raise Denied(f"python -m {args[i + 1]} is not allowed (only {sorted(PYTHON_MODULES)})")
            return
        if a.startswith("-m") and len(a) > 2:
            return check_python(["-m", a[2:]] + args[i + 1:])
        if a == "-c" or (a.startswith("-") and "c" in a[1:] and not a.startswith("--")):
            raise Denied("python -c (inline code) is not allowed; write a test under tests/ instead")
        if a == "-":
            raise Denied("python reading code from stdin is not allowed")
        if a.startswith("-") and len(a) > 1 and set(a[1:]) <= PYTHON_FLAGS_NO_ARG:
            i += 1
            continue
        if a.startswith("-"):
            raise Denied(f"python option {a} is not allowed")
        if PYTHON_SCRIPT_RE.search(a.replace("\\", "/")):
            return
        raise Denied(f"python {a}: only tests under tests/ and scripts/dev/sync_claude_assets.py may be run "
                     "(desk scripts can reach the exchange, GitHub or the ledger)")
    raise Denied("interactive python (no script or module) is not allowed")


def check_program(words: list) -> None:
    words = _unwrap(_strip_redirections(words))
    if not words:
        return
    program, args = words[0], words[1:]
    name = os.path.basename(program)
    if PYTHON_NAME_RE.match(name):
        return check_python(args)
    if name == "git":
        return check_git(args)
    if name in DENIED_PROGRAMS or name.lower() in DENIED_PROGRAMS:
        raise Denied(f"`{name}` is not available to the issue fixer")
    if "/" in program or "\\" in program or name.endswith((".sh", ".py", ".ps1", ".bat", ".cmd", ".exe")):
        raise Denied(f"direct execution of `{program}` is not allowed (only tests via python -m unittest)")
    if name == "find" and any(a in FIND_EXEC_ARGS for a in args):
        raise Denied("find -exec/-ok/-fprint can run programs or write files; pipe to grep instead")
    if name == "sed" and any(SED_EXEC_RE.search(a) for a in args if not a.startswith("-") or a == "-e"):
        raise Denied("sed e/w commands can run programs or write arbitrary files; use the Edit tool")


def check_paths(words: list, cwd: str, conf: Confinement) -> None:
    """No argument (including redirection targets) may resolve into the main checkout or the home directory."""
    for w in words:
        for candidate in [w] + ([w.split("=", 1)[1]] if "=" in w else []):
            if candidate.startswith("~"):
                raise Denied(f"{candidate}: home-directory paths are off limits")
            if "/" not in candidate and not candidate.startswith("."):
                continue
            target = candidate if os.path.isabs(candidate) else os.path.join(cwd, candidate)
            if conf.in_main(target):
                raise Denied(f"{candidate} resolves into the main checkout, which is off limits")


def evaluate(command, conf: Confinement) -> str:
    """Returns '' when the Bash command is allowed, else the denial reason."""
    if not isinstance(command, str) or not command.strip():
        return "empty or missing command"
    for pattern, what in RAW_DENY:
        if pattern.search(command):
            return f"{what} is not allowed in the issue fixer"
    try:
        segments = split_segments(command)
        first = segments[0] if segments else []
        if len(first) != 2 or first[0] != "cd" or not os.path.isabs(first[1]) or not conf.worktree_of(first[1]):
            raise Denied("every command must start with `cd <absolute path of the issue worktree> && ...`")
        cwd = os.path.realpath(first[1])
        for seg in segments[1:]:
            if seg and seg[0] == "cd":
                if len(seg) != 2:
                    raise Denied("cd takes exactly one directory")
                target = seg[1] if os.path.isabs(seg[1]) else os.path.join(cwd, seg[1])
                if conf.in_main(target) or not conf.worktree_of(target):
                    raise Denied(f"cd {seg[1]} leaves the issue worktree")
                cwd = os.path.realpath(target)
                continue
            check_paths(seg, cwd, conf)
            check_program(seg)
    except Denied as e:
        return str(e)
    return ""


def evaluate_payload(payload: dict, conf: Confinement) -> str:
    tool = payload.get("tool_name")
    tool_input = payload.get("tool_input") or {}
    if tool == "Bash":
        return evaluate(tool_input.get("command"), conf)
    if tool in EDIT_TOOLS:
        try:
            check_edit_path(tool_input.get("file_path") or tool_input.get("notebook_path"), conf)
        except Denied as e:
            return str(e)
    return ""


def main() -> int:
    try:
        payload = json.load(sys.stdin)
    except (ValueError, OSError) as e:
        print(f"issue_fixer_guard: unreadable hook input ({e}); denied (fail closed).", file=sys.stderr)
        return 2
    if not isinstance(payload, dict):
        print("issue_fixer_guard: hook input is not an object; denied (fail closed).", file=sys.stderr)
        return 2
    if payload.get("tool_name") not in EDIT_TOOLS | {"Bash"}:
        return 0
    try:
        conf = Confinement.from_project_dir(os.environ.get("CLAUDE_PROJECT_DIR") or payload.get("cwd") or ".")
    except (Denied, OSError, subprocess.SubprocessError) as e:
        print(f"issue_fixer_guard: {e}; denied (fail closed).", file=sys.stderr)
        return 2
    reason = evaluate_payload(payload, conf)
    if reason:
        print(f"BLOCKED by issue_fixer_guard: {reason}. Work only inside the issue worktree; allowed shell: "
              "read-only tools, read-only git, python -m unittest/compileall/py_compile/pytest, tests under "
              "tests/ and scripts/dev/sync_claude_assets.py. Report anything else to the orchestrator in your "
              "final response instead of working around it.", file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main())
