def _glob_marks(word: Word) -> list:
    """Per character: True for an active glob character (an unquoted *, ? or [, but not the ? of `$?`)."""
    t, f = word.text, word.flags
    return [c in "*?[" and f[i] == "u" and not (c == "?" and i and t[i - 1] == "$" and f[i - 1] == "u")
            for i, c in enumerate(t)]


def _has_glob(word: Word) -> bool:
    return any(_glob_marks(word))


def _is_status(t: str, f: str, i: int) -> bool:
    """`$?` (the last exit status, digits only) at index i, both characters in the same quoting."""
    return t[i:i + 2] == "$?" and f[i] == f[i + 1]


def _check_expansions(word: Word, allow_status: bool = False) -> None:
    """Expansions the guard cannot resolve: `$` outside single quotes, `~user` / `~+` / `~-`, `~` (home) and
    unquoted brace expansion. Single-quoted and escaped text is literal. `allow_status`: echo / printf text may use
    `$?`; it never reaches a path, a cd or a program name."""
    t, f = word.text, word.flags
    for i, c in enumerate(t):
        nxt = t[i + 1] if i + 1 < len(t) else ""
        if allow_status and c == "$" and f[i] in "ud" and _is_status(t, f, i):
            continue
        if c == "$" and f[i] in "ud" and nxt and (nxt in EXPANSION_START or (f[i] == "u" and f[i + 1] in "sd")):
            raise Denied(f"{t}: shell expansion `$...` outside single quotes is not allowed (the guard cannot "
                         "resolve it)")
        if c == "~" and f[i] == "u" and (i == 0 or (t[i - 1] in "=:" and f[i - 1] == "u")):
            if nxt in ("", "/"):
                raise Denied(f"{t}: home-directory paths are off limits")
            raise Denied(f"{t}: tilde expansion (~user, ~+, ~-) is not allowed")
    opened = None
    for i, c in enumerate(t):
        if f[i] != "u":
            continue
        if c == "{":
            opened = i
        elif c == "}" and opened is not None:
            inner = [(t[k], f[k]) for k in range(opened + 1, i)]
            if any(ch == "," and fl == "u" for ch, fl in inner) or any(
                    inner[k] == (".", "u") and inner[k + 1] == (".", "u") for k in range(len(inner) - 1)):
                raise Denied(f"{t}: brace expansion is not allowed (spell out each path)")
            opened = None


def _unwrap(words: list) -> tuple:
    """Skips VAR=value prefixes and wrapper programs with their options. Returns ([program, args...], the
    variable names assigned on the way, whether xargs feeds the program)."""
    words, assigned, via_xargs = list(words), [], False
    while words:
        if ASSIGNMENT_RE.match(words[0]):
            assigned.append(words.pop(0).split("=", 1)[0])
            continue
        prog = os.path.basename(words[0])
        if prog not in WRAPPERS:
            break
        if via_xargs:
            raise Denied(f"xargs feeding `{prog}` is not allowed (its program and arguments would come from stdin; "
                         f"xargs may feed only {', '.join(sorted(XARGS_PROGRAMS))})")
        words.pop(0)
        via_xargs = via_xargs or prog == "xargs"
        with_arg = WRAPPER_FLAGS_WITH_ARG.get(prog, set())
        while words and words[0].startswith("-"):
            flag = words.pop(0)
            short = flag[1:] if not flag.startswith("--") else ""
            if prog == "env" and (flag.startswith("--split-string") or "S" in short):
                raise Denied("env -S (string splitting) is not allowed")
            if prog == "env" and (flag.startswith("--chdir") or "C" in short):
                raise Denied("env -C / --chdir is not allowed (relative paths would escape the checks)")
            if flag in with_arg and words:
                words.pop(0)
        if prog == "env":
            while words and ASSIGNMENT_RE.match(words[0]):
                assigned.append(words.pop(0).split("=", 1)[0])
        if prog == "timeout" and words:
            words.pop(0)  # the duration
    return words, assigned, via_xargs


def check_git(args: list) -> None:
    i = 0
    while i < len(args) and args[i].startswith("-"):
        opt = args[i]
        if opt == "-c" or opt.startswith("-c") or opt.startswith("--config-env") or opt.startswith("--exec-path"):
            raise Denied("git -c / --config-env / --exec-path can run arbitrary commands")
        if opt in ("-C", "--git-dir", "--work-tree", "--namespace"):
            i += 2
            continue
        i += 1
    if i >= len(args):
        raise Denied("bare `git` (no subcommand)")
    sub = args[i]
    if sub not in GIT_READ_SUBCOMMANDS:
        raise Denied(f"`git {sub}` is not a read-only git subcommand (the orchestrator commits, pushes and "
                     "manages branches; never stage, commit, stash, checkout, reset, merge or push)")
    for a in args[i + 1:]:
        if any(a == d or a.startswith(d + "=") or (d == "-O" and a.startswith("-O")) for d in GIT_DENIED_ARGS):
            raise Denied(f"`git {sub} {a}` can run an external program or write a file")


def check_python(args: list, cwd: str = "", tree: str = "") -> None:
    i = 0
    while i < len(args):
        a = args[i]
        if a in PYTHON_FLAGS_WITH_ARG:
            i += 2
            continue
        if a.startswith("-W") or a.startswith("-X"):
            i += 1
            continue
        if a == "-m":
            if i + 1 >= len(args):
                raise Denied("python -m without a module")
            if args[i + 1].split(".")[0] not in PYTHON_MODULES:
                raise Denied(f"python -m {args[i + 1]} is not allowed (only {sorted(PYTHON_MODULES)})")
            return
        if a.startswith("-m") and len(a) > 2:
            return check_python(["-m", a[2:]] + args[i + 1:], cwd, tree)
        if a == "-c" or (a.startswith("-") and "c" in a[1:] and not a.startswith("--")):
            raise Denied("python -c (inline code) is not allowed; write a test under tests/ instead")
        if a == "-":
            raise Denied("python reading code from stdin is not allowed")
        if a.startswith("-") and len(a) > 1 and set(a[1:]) <= PYTHON_FLAGS_NO_ARG:
            i += 1
            continue
        if a.startswith("-"):
            raise Denied(f"python option {a} is not allowed")
        real = os.path.realpath(a if os.path.isabs(a) else os.path.join(cwd or ".", a))
        if tree and Confinement._under(real, tree):
            rel = os.path.relpath(real, tree).replace(os.sep, "/")
            if PYTHON_SCRIPT_RE.match(rel):
                return
        raise Denied(f"python {a}: only tests under tests/ and scripts/dev/sync_claude_assets.py of the issue "
                     "worktree may be run (desk scripts can reach the exchange, GitHub or the ledger)")
    raise Denied("interactive python (no script or module) is not allowed")


def _sed_in_place(args: list) -> bool:
    for a in args:
        if a.startswith("--in-place"):
            return True
        if a.startswith("-") and not a.startswith("--"):
            for c in a[1:]:
                if c == "i":
                    return True
                if c in "efl":  # the rest of the cluster is the option's value
                    break
    return False


def check_program(words: list, cwd: str = "", tree: str = "", assigned=(), via_xargs: bool = False) -> None:
    """`words` is [program, args...] after _unwrap."""
    if not words:
        if assigned:
            raise Denied("a segment that only assigns variables (VAR=value; ...) is not allowed")
        return
    program, args = words[0], words[1:]
    name = os.path.basename(program)
    if name in SHELL_KEYWORDS:
        raise Denied(f"`{name}`: shell compound commands (if, for, while, case, {{ }}) are not allowed; run "
                     "simple commands")
    if name == "cd":
        raise Denied("cd is allowed only as a plain `cd <directory>` segment")
    if PYTHON_NAME_RE.match(name):
        check_python(args, cwd, tree)
    elif name == "git":
        check_git(args)
    else:
        if name in DENIED_PROGRAMS or name.lower() in DENIED_PROGRAMS:
            raise Denied(f"`{name}` is not available to the issue fixer")
        if "/" in program or "\\" in program or name.endswith((".sh", ".py", ".ps1", ".bat", ".cmd", ".exe")):
            raise Denied(f"direct execution of `{program}` is not allowed (only tests via python -m unittest)")
        if name == "find" and any(a in FIND_EXEC_ARGS for a in args):
            raise Denied("find -exec/-ok/-fprint/-delete can run programs or write files; pipe to grep instead")
        if name == "sed" and any(SED_EXEC_RE.search(a) for a in args if not a.startswith("-") or a == "-e"):
            raise Denied("sed e/w commands can run programs or write arbitrary files; use the Edit tool")
    if via_xargs and name not in XARGS_PROGRAMS:
        raise Denied(f"xargs feeding `{name}` is not allowed (its arguments come from stdin, unseen by the guard; "
                     f"xargs may feed only {', '.join(sorted(XARGS_PROGRAMS))})")
    bad = sorted(n for n in assigned if n not in ENV_ALLOWED)
    if bad:
        raise Denied(f"environment variable {bad[0]} is not allowed (allowed: {', '.join(sorted(ENV_ALLOWED))})")


def _arg_roles(name: str, args: list) -> list:
    """[(Word, role)] for a program's arguments: read, write, maybe_write (unknown program: path-like arguments
    get the write rules) or skip (not a path: a pattern, a sed script, echo text)."""
    if name in NO_PATH_PROGRAMS:
        return [(a, SKIP) for a in args]
    if name == "dd":
        roles = {"of": WRITE, "if": READ}
        return [(a.tail(a.text.index("=") + 1), roles[a.text.split("=", 1)[0]])
                if a.text.split("=", 1)[0] in roles and "=" in a.text else (a, SKIP) for a in args]
    if name in READ_PROGRAMS or PYTHON_NAME_RE.match(name):
        default = READ
    else:
        default = WRITE if name in WRITE_PROGRAMS else MAYBE_WRITE
    value_default = MAYBE_WRITE if default == MAYBE_WRITE else READ
    short, long_ = SHORT_VALUE_OPTS.get(name, ""), LONG_VALUE_OPTS.get(name, set())
    roles_of = VALUE_ROLES.get(name, {})
    out, positional, explicit_script, in_place, target_given, opts_done, i = [], [], False, False, False, False, 0

    def value(opt, word):
        nonlocal explicit_script, target_given
        role = roles_of.get(opt, value_default)
        explicit_script = explicit_script or (name in PATTERN_PROGRAMS and opt in SCRIPT_OPTS)
        target_given = target_given or (role == WRITE and name in ("cp", "mv", "install"))
        out.append((word, role))

    while i < len(args):
        a, t = args[i], args[i].text
        if opts_done or not t.startswith("-") or t == "-":
            positional.append(a)
        elif t == "--":
            opts_done = True
        elif t.startswith("--"):
            key, eq, _ = t.partition("=")
            in_place = in_place or (name == "sed" and key == "--in-place")
            if eq:
                value(key, a.tail(len(key) + 1))
            elif key in long_ and i + 1 < len(args):
                i += 1
                value(key, args[i])
        else:
            for j in range(1, len(t)):
                if name == "sed" and t[j] == "i":
                    in_place = True  # the rest of the cluster is the backup suffix
                    break
                if t[j] in short:
                    if j + 1 < len(t):
                        value("-" + t[j], a.tail(j + 1))
                    elif i + 1 < len(args):
                        i += 1
                        value("-" + t[j], args[i])
                    break
        i += 1
    if name in PATTERN_PROGRAMS and not explicit_script and positional:
        out.append((positional.pop(0), SKIP))
    for k, a in enumerate(positional):
        if name == "cp":
            role = READ if target_given or k < len(positional) - 1 else WRITE
        elif name == "uniq":
            role = WRITE if k == 1 else READ
        elif name == "sed":
            role = WRITE if in_place else READ
        else:
            role = default
        out.append((a, role))
    return out


class _PathContext:
    def __init__(self, cwd: str, tree: str, conf: Confinement):
        self.cwd, self.tree, self.conf = cwd, tree, conf

    def resolve(self, text: str) -> str:
        return os.path.realpath(text if os.path.isabs(text) else os.path.join(self.cwd, text))


def _check_target(shown: str, real: str, write: bool, ctx: _PathContext, prefix_ok: bool) -> None:
    conf = ctx.conf
    if conf.in_main(real):
        raise Denied(f"{shown} resolves into the main checkout, which is off limits")
    other = conf.worktree_of(real)
    if other and other != ctx.tree:
        raise Denied(f"{shown} is in another issue worktree ({other}); a command may only use its own issue "
                     "worktree")
    if other:
        if write:
            _check_tree_write(shown, real, ctx.tree)
        return
    if real == os.devnull:
        return
    if any(Confinement._under(real, root) and not (write and real == root) for root in TEMP_ROOTS):
        return
    if prefix_ok and not write and any(Confinement._under(real, p) for p in PYTHON_PREFIXES):
        return
    home = os.path.realpath(os.path.expanduser("~"))
    where = "the home directory" if Confinement._under(real, home) else "outside the issue worktree"
    raise Denied(f"{shown} resolves to {where} ({real}); Bash may only {'write' if write else 'use'} paths inside "
                 "the issue worktree, /dev/null or the temp dir")


def _check_word(word: Word, role: str, ctx: _PathContext, prefix_ok: bool, write_program: bool) -> None:
    marks = _glob_marks(word)
    if role == SKIP:
        if not any(marks):
            return
        if write_program:
            raise Denied(f"{word.text}: an unquoted glob in a write command is not allowed")
        role = READ  # the shell expands it into file names
    write = role in (WRITE, MAYBE_WRITE)
    if any(marks):
        if role == WRITE:
            raise Denied(f"{word.text}: a glob cannot be a write target (name each file)")
        if role == MAYBE_WRITE:
            # Python's glob does not read every pattern as bash does ([^x], [[:alpha:]], quoted characters in a
            # bracket), so a program that may write never gets one
            raise Denied(f"{word.text}: an unquoted glob is not allowed in the arguments of a program the guard "
                         "does not know (it may write; name each file)")
        # The directory part before the first glob component is the same for every expansion
        first = marks.index(True)
        _check_target(word.text, ctx.resolve(word.text[:word.text.rfind("/", 0, first) + 1]), False, ctx,
                      prefix_ok)
        pattern = "".join(c if m else glob.escape(c) for c, m in zip(word.text, marks))
        matches = glob.glob(pattern if os.path.isabs(pattern) else os.path.join(ctx.cwd, pattern))
        if matches:
            for m in matches:
                _check_target(word.text, os.path.realpath(m), False, ctx, prefix_ok)
            return
        # No match: bash passes the word unchanged, so the literal is checked below too
    real = ctx.resolve(word.text)
    if role != WRITE and not (os.path.exists(real) or os.path.isdir(os.path.dirname(real))):
        return  # not a path (e.g. "/fapi/v1/order")
    _check_target(word.text, real, write, ctx, prefix_ok)


def check_paths(words: list, redirs: list, ctx: _PathContext) -> None:
    """`words` is [program, args...] as Words after _unwrap; `redirs` the segment's redirections."""
    for op, target in redirs:
        if op in (">&", "<&") and (target.text.isdigit() or target.text == "-"):
            continue  # file descriptor duplication
        _check_word(target, READ if op in ("<", "<&") else WRITE, ctx, False, True)
    if not words:
        return
    name = os.path.basename(words[0].text)
    prefix_ok = name in READ_PROGRAMS or bool(PYTHON_NAME_RE.match(name))
    in_place = name == "sed" and _sed_in_place([w.text for w in words[1:]])
    write_program = name in WRITE_PROGRAMS or in_place
    for word, role in _arg_roles(name, words[1:]):
        _check_word(word, role, ctx, prefix_ok, write_program)


def _check_cd(segments: list, i: int, cwd: str, tree: str, conf: Confinement) -> str:
    """A `cd` after the first one; returns the new tracked directory."""
    seg = segments[i]
    if len(seg.words) != 2 or seg.redirs:
        raise Denied("cd takes exactly one directory")
    if seg.depth:
        raise Denied("cd inside a subshell ( ... ) is not allowed (the guard could not track the directory)")
    if any(o in ("|", "|&", "||") for o in seg.ops_before) or seg.next in ("|", "|&", "&", "||"):
        raise Denied("cd in a pipeline, in the background or next to || is not allowed")
    if "&&" in seg.ops_before:
        # Conditional cd: when it is skipped, nothing after it may run with the untracked directory
        k = i
        while k > 0 and not any(o in LIST_SEPARATORS for o in segments[k].ops_before):
            if "||" in segments[k].ops_before:
                raise Denied("a conditional cd after || is not allowed")
            k -= 1
        if any(o not in ("&&", "|", "|&") for s in segments[i + 1:] for o in s.ops_before):
            raise Denied("a conditional cd (`... && cd X`) may not be followed by ;, &, || or a subshell")
    word = seg.words[1]
    _check_expansions(word)
    if word.text == "-" or _has_glob(word):
        raise Denied(f"cd {word.text} is not allowed (name the directory)")
    target = os.path.realpath(word.text if os.path.isabs(word.text) else os.path.join(cwd, word.text))
    if conf.in_main(target) or conf.worktree_of(target) != tree:
        raise Denied(f"cd {word.text} leaves the issue worktree")
    if not os.path.isdir(target):
        raise Denied(f"cd {word.text}: not an existing directory of the issue worktree")
    return target


def _first_cd(segments: list, conf: Confinement) -> tuple:
    """(issue worktree, tracked directory) from the mandatory leading `cd <absolute path>`."""
    first = segments[0] if segments else None
    if (not first or first.depth or first.ops_before or first.redirs or len(first.words) != 2
            or first.words[0].text != "cd" or first.next not in ("&&", ";", None)):
        raise Denied(START_MESSAGE)
    _check_expansions(first.words[1])
    target = first.words[1].text
    if _has_glob(first.words[1]) or not os.path.isabs(target):
        raise Denied(START_MESSAGE)
    real = os.path.realpath(target)
    tree = conf.worktree_of(real)
    if not tree or conf.in_main(real) or not os.path.isdir(real):
        raise Denied(START_MESSAGE)
    return tree, real


def evaluate(command, conf: Confinement) -> str:
    """Returns '' when the Bash command is allowed, else the denial reason. Pure: reads the filesystem only."""
    if not isinstance(command, str) or not command.strip():
        return "empty or missing command"
    for pattern, what in RAW_DENY:
        if pattern.search(command):
            return f"{what} is not allowed in the issue fixer"
    try:
        segments = parse_command(command)
        tree, cwd = _first_cd(segments, conf)
        for i in range(1, len(segments)):
            seg = segments[i]
            if seg.words and seg.words[0].text == "cd":
                cwd = _check_cd(segments, i, cwd, tree, conf)
                continue
            texts = [w.text for w in seg.words]
            rest, assigned, via_xargs = _unwrap(texts)
            start = len(texts) - len(rest)
            # `$?` only in the arguments of echo / printf (text), never in a program name, path or redirection
            status_ok = bool(rest) and os.path.basename(rest[0]) in NO_PATH_PROGRAMS
            for k, w in enumerate(seg.words):
                _check_expansions(w, status_ok and k > start)
            for _, t in seg.redirs:
                _check_expansions(t)
            check_paths(seg.words[start:], seg.redirs, _PathContext(cwd, tree, conf))
            check_program(rest, cwd, tree, assigned, via_xargs)
    except Denied as e:
        return str(e)
    return ""


