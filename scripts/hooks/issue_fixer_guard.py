#!/usr/bin/env python3
"""
issue_fixer_guard.py - PreToolUse hook scoped to the `issue_fixer` subagent. Claude Code only: it runs as a
frontmatter hook generated by scripts/dev/sync_claude_assets.py (matcher Bash|Edit|Write|MultiEdit|NotebookEdit|
Read|Grep|Glob); agy cannot scope hooks to one subagent, so under agy no guard runs. The project hooks
(pre_trade_guard.py) still run as well and stay the hard boundary for trading actions.

This is a confinement policy, not a sandbox: a denylist of programs plus path, quoting and binding rules. The
fixer edits code and runs tests inside ONE linked issue worktree; it never commits, pushes, calls GitHub or the
network, installs packages, runs desk runtime scripts or touches the main checkout (where the running hooks,
this guard included, live).

  * Edit / Write / MultiEdit / NotebookEdit: the absolute target must be inside a linked worktree of this
    repository (never the main checkout), and never under .git/, .claude/, .agents/hooks.json or logs/ (except
    logs/issue_work/). Never the running guard file (os.path.realpath(__file__), which matters when a session
    runs from a worktree) nor a worktree's logs/issue_work/guard_heartbeat.json or fixer_binding.json. These
    names are compared case-folded (`LOGS/`, `.GIT/` and `.CLAUDE/` are the same directories on DrvFs).
  * Read / Grep / Glob: allowed, except the heartbeat keys in <main checkout>/logs/issue_work_keys/ (compared
    case-folded, plus st_dev / st_ino for other names of that directory): a path with an `issue_work_keys`
    component, a Grep `glob` or Glob `pattern` naming it, a Glob `pattern` that can leave its root (a `..`
    component or an absolute alternative in any brace expansion; an absolute pattern is rooted at its directory
    part before the first wildcard), any Grep or Glob rooted at that directory, under it or at an ancestor of it
    (the main checkout included), with or without a glob, and, for a Grep rooted outside a linked worktree, a
    `glob` that can match `<N>.key` (unparseable globs such as braces count as a match). Inside a linked
    worktree (a `.git` file pointing into `.git/worktrees/`, never a submodule) any Grep glob passes. Git runs
    only for the rules that need the main checkout (check_read_tool). Reads neither claim nor write the
    heartbeat.
  * Bash:
      - a command containing a carriage return is denied (send LF line endings): bash reads `\\r` as a word
        character, so `cd x<CR>` would name another directory than the one the guard sees;
      - the command must start with `cd <absolute path of a linked worktree>`: that is the issue worktree. Later
        `cd`s must stay inside it, at the top level (no subshell, pipeline, `||` or background list); every
        directory the shell may be in is tracked: a conditional `cd` (`... && cd X`) may be followed by `;`
        only when everything before it in its `&&` chain is a `cd` (then the later segments are checked
        against each directory the chain may stop in), and never by `&`, `||` or a subshell;
      - every segment (split on ; && || | & newlines and subshell parentheses; a `#` comment only at a word
        start) is checked; wrappers (env, timeout, nice,
        nohup, time, command, stdbuf, xargs) are unwrapped; xargs may feed only XARGS_PROGRAMS (read-only, its
        arguments come from stdin), never another wrapper; `VAR=value` prefixes and `env VAR=value` only for
        ENV_ALLOWED names, and never as a segment of their own;
      - command and process substitution, heredocs, `$` expansions outside single quotes (except `$?` in echo /
        printf text), `~user` / `~+` / `~-`, unquoted brace expansion and shell compound commands (if, for,
        while, { }) are denied;
      - paths: write targets (redirections; cp mv tee sed -i rm touch mkdir dd of= install truncate chmod;
        sort -o) must resolve inside the issue worktree (with the edit-tool rules above), /dev/null or the temp
        dir; other path-like arguments too, or under the Python prefix for read-only programs (stdlib and
        site-packages). Unquoted globs are expanded and every match is checked (each bracket expression is
        globbed as `?`, a superset of what bash matches), and so are the directory part before the first glob
        and, with no match, the literal word; a glob as a write target or an argument of a program the guard
        does not know (it may write) is denied. The main checkout, the home directory and every other issue
        worktree are off limits;
      - git: read-only subcommands only; python: only `-m unittest|compileall|py_compile|pytest`, test files
        under tests/ and scripts/dev/sync_claude_assets.py of the issue worktree (resolved, so `..` and symlinks
        cannot point elsewhere);
      - programs that can execute other programs (find -exec, awk, sed's e/w commands, rg --pre /
        --pre-glob / --hostname-bin, sort --compress-program, make, editors, launchers such as setsid / flock /
        taskset, tar / zip, other interpreters and shells), shell builtins that change the environment (export,
        set, alias...), network tools, package managers, GitHub CLI and privilege escalation are denied.
  * Binding: `issue_workspace.py init` writes <worktree>/logs/issue_work/fixer_binding.json. The first allowed
    call that carries a session_id claims it; calls from another session are then denied in that worktree. A
    worktree without the marker (created before it existed) is accepted unbound: a documented legacy limit.
    `issue_workspace.py rebind <N>` (orchestrator only) resets the claim.
  * Heartbeat: main() writes <worktree>/logs/issue_work/guard_heartbeat.json after every decision (best effort,
    never changes the decision), only to the worktree the decision validated: never to a worktree bound to
    another session (or whose marker names another worktree), nor to an unbound one while the calling session
    is bound elsewhere. It records `binding_claim` (claimed | already_bound | failed | n/a) and, when
    `issue_workspace.py init` created <main checkout>/logs/issue_work_keys/<N>.key, an HMAC-SHA256 `sig` over
    {ts, worktree, issue, decision, session_id, binding_claim} (else `signed: false`: a legacy worktree).
    `issue_workspace.py check-guard` verifies it, so the orchestrator knows the guard ran.

Limits: tests the fixer writes are code and run with the test runner; the auditor and the PR reviewers review that
code before merge. The guard prevents direct misuse; it is not a sandbox. The signature detects a stale, missing
or unsigned heartbeat and casual forgery, not a determined one: if the frontmatter hook does not load at all, the
fixer is unguarded and could read the key and sign a heartbeat itself. A hardlink to a key file inside the
worktree is not covered (it shares no name or directory with the keys); the fixer has no tool that creates one
(`ln` is denied, the edit tools write regular files, and Bash cannot name the main checkout, so `cp -l` cannot
reach a key).

Contract (Claude Code hooks): hook JSON on stdin; exit 0 allows, exit 2 denies (reason on stderr). Malformed input
or an unresolvable repository is denied (fail closed); a read that needs no main-checkout rule never resolves it.
"""

