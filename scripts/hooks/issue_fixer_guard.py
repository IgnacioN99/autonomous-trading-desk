def check_edit_path(path, conf: Confinement) -> None:
    if not isinstance(path, str) or not path:
        raise Denied("missing file path")
    if not os.path.isabs(path):
        raise Denied(f"{path}: use an absolute path inside the issue worktree")
    tree = conf.worktree_of(path)
    if not tree or conf.in_main(path):
        raise Denied(f"{path} is outside the issue worktrees (the main checkout and other directories are off "
                     "limits)")
    rel = os.path.relpath(os.path.realpath(path), tree).replace(os.sep, "/")
    parts = rel.split("/")
    if ".git" in parts:
        raise Denied(f"{path}: git internals are off limits")
    if parts[0] == ".claude":
        raise Denied(f"{path}: .claude/ is generated or local configuration (edit .agents/ and run the generator)")
    if rel == ".agents/hooks.json":
        raise Denied(f"{path}: hook configuration is off limits")
    if parts[0] == "logs" and (len(parts) < 3 or parts[1] != "issue_work"):
        raise Denied(f"{path}: only logs/issue_work/ may be written under logs/")


