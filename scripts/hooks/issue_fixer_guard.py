#!/usr/bin/env python3
"""
issue_fixer_guard.py - PreToolUse hook scoped to the `issue_fixer` subagent (Claude Code frontmatter hook,
generated by scripts/dev/sync_claude_assets.py; matcher Bash|Edit|Write|MultiEdit|NotebookEdit). The project
hooks (pre_trade_guard.py) still run as well and stay the hard boundary for trading actions.

The fixer edits code and runs tests inside ONE linked issue worktree; it never commits, pushes, calls GitHub or
the network, installs packages, runs desk runtime scripts or touches the main checkout (where the running hooks,
this guard included, live). Confinement:

  * Edit / Write / MultiEdit / NotebookEdit: the absolute target must be inside a linked worktree of this
    repository (never the main checkout), and never under .git/, .claude/, .agents/hooks.json or logs/ (except
    logs/issue_work/).
  * Bash, with an ALLOWLIST so anything unrecognised is denied:
      - the command must start with `cd <absolute path of a linked worktree>`; later `cd`s may not leave it for
        the main checkout, and no argument may resolve into the main checkout or name $CLAUDE_PROJECT_DIR / ~;
      - every segment (split on ; && || | & newlines and subshell parentheses) is checked; `VAR=value` prefixes
        and wrappers (env, timeout, nice, nohup, time, command, stdbuf, xargs) are unwrapped;
      - command substitution, process substitution, heredocs and `eval` / `sh -c` style indirection are denied;
      - git: read-only subcommands only; python: only `-m unittest|compileall|py_compile|pytest`, test files
        under tests/ and scripts/dev/sync_claude_assets.py;
      - programs that can execute other programs (find -exec, awk, sed's e/w commands, make, editors, other
        interpreters and shells), network tools, package managers, GitHub CLI and privilege escalation are denied.

Limits: tests the fixer writes are code and run with the test runner; the auditor and the PR reviewers review that
code before merge. This guard prevents direct misuse; it is not a sandbox.

Contract (Claude Code hooks): hook JSON on stdin; exit 0 allows, exit 2 denies (reason on stderr). Malformed input
or an unresolvable repository is denied (fail closed).
"""

import json
import os
import re
import shlex
import subprocess
import sys

EDIT_TOOLS = {"Edit", "Write", "MultiEdit", "NotebookEdit"}
GIT_READ_SUBCOMMANDS = {
    "diff", "status", "log", "show", "grep", "ls-files", "blame", "rev-parse", "describe", "shortlog",
    "cat-file", "ls-tree", "merge-base", "diff-tree", "name-rev", "rev-list", "whatchanged",
}
GIT_DENIED_ARGS = ("--ext-diff", "-O", "--open-files-in-pager", "--output")
PYTHON_MODULES = {"unittest", "compileall", "py_compile", "pytest"}
PYTHON_FLAGS_NO_ARG = set("bBdEhiIOqsSuvVxR")
PYTHON_FLAGS_WITH_ARG = {"-W", "-X"}
PYTHON_SCRIPT_RE = re.compile(r"(^|/)(tests/[\w./-]+\.py|scripts/dev/sync_claude_assets\.py)$")
PYTHON_NAME_RE = re.compile(r"^(python|python3(\.\d+)?|py)$")

DENIED_PROGRAMS = {
    # GitHub / network / remote access
    "gh", "curl", "wget", "ssh", "scp", "sftp", "rsync", "nc", "ncat", "netcat", "telnet", "ftp", "socat",
    # package managers and build tools that run arbitrary recipes
    "pip", "pip3", "pipx", "npm", "npx", "yarn", "pnpm", "apt", "apt-get", "brew", "conda", "uv", "poetry",
    "make", "gmake", "cmake",
    # privilege, containers, OS bridges and services
    "sudo", "su", "doas", "docker", "podman", "kubectl", "wsl", "wsl.exe", "powershell", "powershell.exe",
    "pwsh", "cmd", "cmd.exe", "crontab", "systemctl", "service", "at", "pkill", "killall", "open", "xdg-open",
    # shells, indirection, interpreters and programs that execute other programs
    "eval", "exec", "source", ".", "bash", "sh", "zsh", "dash", "ksh", "fish", "perl", "ruby", "node", "deno",
    "php", "lua", "osascript", "awk", "gawk", "mawk", "nawk", "busybox", "watch", "parallel", "script",
    "expect", "tclsh", "strace", "gdb", "vi", "vim", "nvim", "emacs", "ed", "ex", "nano",
}
WRAPPERS = {"env", "timeout", "nice", "nohup", "time", "command", "stdbuf", "xargs"}
WRAPPER_FLAGS_WITH_ARG = {
    "timeout": {"-s", "--signal", "-k", "--kill-after"},
    "nice": {"-n", "--adjustment"},
    "stdbuf": {"-i", "-o", "-e"},
    "xargs": {"-n", "-I", "-L", "-P", "-d", "-s", "-E", "-a", "--max-args", "--replace", "--max-lines",
              "--max-procs", "--delimiter", "--arg-file"},
    "env": {"-u", "--unset", "-C", "--chdir"},
}
FIND_EXEC_ARGS = {"-exec", "-execdir", "-ok", "-okdir", "-fprint", "-fprint0", "-fprintf", "-fls"}
# sed `e` (execute) / `w` `W` (write file) commands, with an optional address (1e, $e, /re/e, 1,5w), and the
# s///e and s///w flags
_SED_ADDR = r"(?:\d+|\$|/(?:[^/\\]|\\.)*/)"
SED_EXEC_RE = re.compile(
    r"(^|[;{}\n])\s*(?:" + _SED_ADDR + r"(?:\s*,\s*" + _SED_ADDR + r")?)?\s*!?\s*[eWw](\s|;|$)"
    r"|/[0-9gpIiMm]*[ew][0-9gpIiMm]*\s*($|[;}\s])"
)
RAW_DENY = [
    (re.compile(r"\$\("), "command substitution $(...)"),
    (re.compile(r"`"), "backtick command substitution"),
    (re.compile(r"[<>]\("), "process substitution"),
    (re.compile(r"<<"), "heredoc (use the Write/Edit tools to create files)"),
    (re.compile(r"CLAUDE_PROJECT_DIR"), "$CLAUDE_PROJECT_DIR (the main checkout is off limits)"),
]
OPERATORS = {";", "&&", "||", "|", "&", "|&", "(", ")", ";;"}
ASSIGNMENT_RE = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*=")


class Denied(Exception):
    pass


class Confinement:
    """The main checkout (off limits) and the linked worktrees (where the fixer may work)."""

    def __init__(self, main_root: str, worktrees: list):
        self.main_root = os.path.realpath(main_root)
        self.worktrees = [os.path.realpath(w) for w in worktrees if os.path.realpath(w) != self.main_root]

    @classmethod
    def from_project_dir(cls, project_dir: str) -> "Confinement":
        common = subprocess.run(["git", "rev-parse", "--path-format=absolute", "--git-common-dir"],
                                cwd=project_dir, capture_output=True, text=True, timeout=10)
        if common.returncode != 0:
            raise Denied(f"cannot resolve the repository from {project_dir}")
        main_root = os.path.dirname(common.stdout.strip().rstrip("/"))
        listing = subprocess.run(["git", "worktree", "list", "--porcelain"], cwd=main_root,
                                 capture_output=True, text=True, timeout=10)
        if listing.returncode != 0:
            raise Denied("cannot list the repository worktrees")
        trees = [ln[len("worktree "):] for ln in listing.stdout.splitlines() if ln.startswith("worktree ")]
        return cls(main_root, trees)

    @staticmethod
    def _under(path: str, root: str) -> bool:
        return path == root or path.startswith(root.rstrip(os.sep) + os.sep)

    def in_main(self, path: str) -> bool:
        return self._under(os.path.realpath(path), self.main_root)

    def worktree_of(self, path: str) -> str:
        real = os.path.realpath(path)
        return next((w for w in self.worktrees if self._under(real, w)), "")


