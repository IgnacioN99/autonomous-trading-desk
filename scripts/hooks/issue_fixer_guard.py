class Word:
    """A shell word as shlex returns it, plus one quoting flag per character: u (unquoted), d (inside double
    quotes), s (inside single quotes), e (backslash-escaped) or p (operator character)."""
    __slots__ = ("text", "flags")

    def __init__(self, text: str, flags: str):
        self.text, self.flags = text, flags

    def tail(self, start: int) -> "Word":
        return Word(self.text[start:], self.flags[start:])


class Segment:
    """One simple command: its words, its redirections ((operator, target Word)), its subshell depth and the
    operators met before it (since the previous segment) and after it."""

    def __init__(self, depth: int = 0):
        self.words, self.redirs, self.depth, self.ops_before, self.ops_after = [], [], depth, [], []

    @property
    def prev(self):
        return self.ops_before[-1] if self.ops_before else None

    @property
    def next(self):
        return self.ops_after[0] if self.ops_after else None


def _unquoted_newlines_to_separators(command: str) -> str:
    """What bash runs, as one line: unquoted newlines become ';' so every line is its own segment; line
    continuations (backslash-newline outside single quotes) are removed; backslash escapes are honoured (`\\"`
    opens no quote, `\\\\` before a newline is no continuation); a `#` comment is dropped up to the end of the
    line, but only where bash starts one: at a word start, i.e. after an unquoted, unescaped space, tab, newline or
    one of ;&|()<> (never after an escaped character). A carriage return is an ordinary word character, as in bash
    (`cd x<CR>` names the directory "x<CR>")."""
    out, quote, word_start, i, n = [], None, True, 0, len(command)
    while i < n:
        ch = command[i]
        if quote == "'":
            quote = None if ch == "'" else quote
            out.append(ch)
            i += 1
            continue
        if ch == "\\" and i + 1 < n:
            if command[i + 1] == "\n":
                i += 2
                continue
            out.append(command[i:i + 2])
            word_start = False
            i += 2
            continue
        if quote == '"':
            quote = None if ch == '"' else quote
        elif ch in ("'", '"'):
            quote = ch
        elif ch == "\n":
            ch = ";"
        elif ch == "#" and word_start:
            while i < n and command[i] != "\n":
                i += 1
            continue
        word_start = quote is None and ch in " \t" + PUNCT_CHARS
        out.append(ch)
        i += 1
    return "".join(out)


def _shlex_tokens(prepared: str) -> list:
    lexer = shlex.shlex(prepared, posix=True, punctuation_chars=PUNCT_CHARS)
    lexer.whitespace_split = True
    lexer.whitespace = SHELL_BLANKS
    lexer.commenters = ""
    try:
        return list(lexer)
    except ValueError as e:
        raise Denied(f"unparseable command ({e})")


def _scan_words(prepared: str) -> list:
    """Second, quote-aware pass over the same text: mirrors the shlex split above and records how each
    character was quoted. The caller checks that both passes agree."""
    words, text, flags, in_word = [], [], [], False
    i, n = 0, len(prepared)

    def flush():
        nonlocal text, flags, in_word
        if in_word:
            words.append(Word("".join(text), "".join(flags)))
        text, flags, in_word = [], [], False

    while i < n:
        c = prepared[i]
        if c in SHELL_BLANKS:
            flush()
            i += 1
        elif c in PUNCT_CHARS:
            flush()
            j = i
            while j < n and prepared[j] in PUNCT_CHARS:
                j += 1
            words.append(Word(prepared[i:j], "p" * (j - i)))
            i = j
        elif c == "'":
            j = prepared.find("'", i + 1)
            if j < 0:
                raise Denied("unparseable command (No closing quotation)")
            text.append(prepared[i + 1:j])
            flags.append("s" * (j - i - 1))
            in_word, i = True, j + 1
        elif c == '"':
            in_word, i = True, i + 1
            while True:
                if i >= n:
                    raise Denied("unparseable command (No closing quotation)")
                c = prepared[i]
                if c == '"':
                    i += 1
                    break
                if c == "\\" and i + 1 < n:
                    nxt = prepared[i + 1]
                    if nxt in '"\\':
                        text.append(nxt)
                        flags.append("e")
                    else:  # shlex keeps the backslash; `\$` stays a literal dollar
                        text.append(c + nxt)
                        flags.append("d" + ("e" if nxt == "$" else "d"))
                    i += 2
                    continue
                text.append(c)
                flags.append("d")
                i += 1
        elif c == "\\":
            if i + 1 >= n:
                raise Denied("unparseable command (No escaped character)")
            text.append(prepared[i + 1])
            flags.append("e")
            in_word, i = True, i + 2
        else:
            text.append(c)
            flags.append("u")
            in_word, i = True, i + 1
    flush()
    return words


def _split_punct(run: str) -> list:
    out, i = [], 0
    while i < len(run):
        op = next(o for o in _PUNCT_TOKENS if run.startswith(o, i))
        out.append(op)
        i += len(op)
    return out


def parse_command(command: str) -> list:
    """Segments of a Bash command. The posix shlex split stays the reference; the quote-aware pass must agree
    with it word for word, else the command is denied (fail closed)."""
    prepared = _unquoted_newlines_to_separators(command)
    tokens = _shlex_tokens(prepared)
    words = _scan_words(prepared)
    if [w.text for w in words] != tokens:
        raise Denied("unparseable command (the quoting analysis disagrees with the shell split)")
    segments, ops, depth, pending = [], [], 0, None
    cur = Segment(0)
    for w in words:
        if not w.flags or set(w.flags) != {"p"}:
            if pending:
                cur.redirs.append((pending, w))
                pending = None
            else:
                cur.words.append(w)
            continue
        for op in _split_punct(w.text):
            if op in REDIRECTIONS:
                if pending:
                    raise Denied(f"redirection `{pending}` without a target")
                pending = op
                continue
            if pending:
                raise Denied(f"redirection `{pending}` without a target")
            if cur.words or cur.redirs:
                cur.ops_before, ops = ops, []
                segments.append(cur)
                cur = Segment(depth)
            ops.append(op)
            depth += {"(": 1, ")": -1}.get(op, 0)
            if depth < 0:
                raise Denied("unbalanced parentheses")
            cur.depth = depth
    if pending:
        raise Denied(f"redirection `{pending}` without a target")
    if depth:
        raise Denied("unbalanced parentheses")
    if cur.words or cur.redirs:
        cur.ops_before, ops = ops, []
        segments.append(cur)
    for k, seg in enumerate(segments):
        seg.ops_after = segments[k + 1].ops_before if k + 1 < len(segments) else ops
    return segments


def split_segments(command: str) -> list:
    """Word texts per segment (redirections excluded)."""
    return [[w.text for w in seg.words] for seg in parse_command(command)]


